#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "$0")/../../.." && pwd)"
target_dir="$repo_root/artifacts/operations/baseline"
mkdir -p "$target_dir"

check=false
if [[ "${1:-}" == "--check" ]]; then
  check=true
  shift
fi
if [[ $# -ne 0 ]]; then
  echo "usage: $0 [--check]" >&2
  exit 64
fi

temp_root="${TMPDIR:-/tmp}"
out_dir="$(mktemp -d "${temp_root%/}/lenbands-repository-baseline.XXXXXX")"
trap 'rm -rf "$out_dir"' EXIT

capability_index="$repo_root/artifacts/operations/catalogs/capability-index.md"
phase_index="$repo_root/artifacts/operations/catalogs/capability-phase-index.md"

# family_for() resolved via canonical capability-family-map.yaml through CapabilityRegistry.
# No case statements — business knowledge lives in data.

has_file() {
  [[ -f "$repo_root/$1" ]] && echo present || echo missing
}

cat > "$out_dir/capability-baseline.md" <<EOF
# Repository Baseline — Capability Catalog

Generated by tools/generate-repository-baseline.sh from:

- artifacts/operations/catalogs/capability-index.md (projection of blueprint/03-features.md)
- artifacts/operations/catalogs/capability-phase-index.md (phase projection)
- artifacts/operations/capability-family-map.yaml (canonical capability→family mapping)

This report is diagnostic. It is not a capability or family source of truth.

| Metric | Value |
|---|---:|
| Total capability IDs | $(awk -F'|' '/^\| \x60[^\x60]+\x60 \|/ {n++} END {print n}' "$capability_index") |
| P0 | $(awk -F'|' '/^\| \x60[^\x60]+\x60 \| P0 \|/ {n++} END {print n+0}' "$phase_index") |
| P1 | $(awk -F'|' '/^\| \x60[^\x60]+\x60 \| P1 \|/ {n++} END {print n+0}' "$phase_index") |
| P2 | $(awk -F'|' '/^\| \x60[^\x60]+\x60 \| P2 \|/ {n++} END {print n+0}' "$phase_index") |
| Deferred | $(awk -F'|' '/^\| \x60[^\x60]+\x60 \| deferred \|/ {n++} END {print n+0}' "$phase_index") |
| Unknown IDs in catalog projection | not detected by this baseline generator; semantic validator required |
| Duplicate IDs | $(awk -F'|' '/^\| \x60[^\x60]+\x60 \|/ {print $2}' "$capability_index" | sort | uniq -d | wc -l | tr -d ' ') |

## Capability inventory

| Capability | Phase | Candidate family |
|---|---|---|
EOF

# Resolve family via canonical CapabilityRegistry (reads capability-family-map.yaml).
ruby -I"$repo_root/tools/lib" -rlenbands -rlenbands/registries - "$phase_index" "$capability_index" "$out_dir" <<'RUBY'
phase_index_path, capability_index_path, out_dir = ARGV

phase_lines = File.read(phase_index_path).lines

phase_for = lambda do |id|
  phase_lines.each do |line|
    parts = line.split("|").map(&:strip)
    next unless parts.length >= 3
    row_id = parts[1].to_s[/\A`([^`]+)`\z/, 1]
    next unless row_id == id
    return parts[2]
  end
  "unknown"
end

ids = File.read(capability_index_path)
  .scan(/^\| `([^`]+)` \|/)
  .flatten

File.open(File.join(out_dir, "capability-baseline.md"), "a") do |f|
  ids.each do |id|
    phase = phase_for.call(id)
    family = Lenbands::Registries::CapabilityRegistry.family_for(id) || "UNRESOLVED.Unknown"
    f.puts "| #{id} | #{phase} | #{family} |"
  end
end
RUBY

