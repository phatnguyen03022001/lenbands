outputs=(
  capability-baseline.md
  artifact-coverage-baseline.md
  family-candidate-baseline.md
  runtime-inventory.md
  authority-drift-report.md
  README.md
)
stale=0
for file in "${outputs[@]}"; do
  if ! cmp -s "$out_dir/$file" "$target_dir/$file"; then
    stale=1
    if ! $check; then
      mv "$out_dir/$file" "$target_dir/$file"
    fi
  fi
done

if $check; then
  if (( stale )); then
    echo "repository baseline projections are stale; run tools/generate-repository-baseline.sh" >&2
    exit 1
  fi
  echo "repository baseline projections are current"
elif (( stale )); then
  echo "repository baseline generated: $target_dir"
else
  echo "repository baseline unchanged"
fi
