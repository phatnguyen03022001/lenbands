| PLACEMENT.Diagnosis | $(has_file artifacts/experience/specs/vertical-slices/placement-and-plan.md) | missing | missing | $(has_file artifacts/engineering/contracts/placement-diagnosis-contract.md) | shared | shared | $(has_file artifacts/operations/acceptance/p0-acceptance-manifest.yaml) | present in P0 manifest |
